import type { Order, OrderItem, OrderMoney, PickupSlot } from '@/types';

/**
 * Seed orders following the reference `ORDERS` (EB-2409-017/014/009/011) plus
 * 018 (preparing, screen 9.2) and 022 (expired, screen 9.4).
 *
 * Money follows this project's breakdown: subtotal = price x qty,
 * total = subtotal - promo - own box. (The reference is inconsistent about what
 * `subtotal` means between orders; the totals are identical.)
 */
const slot = (date: string, start: string, end: string): PickupSlot => ({
  label: `${start} – ${end}`,
  date,
  start,
  end,
});

const item = (
  foodBagId: string,
  name: string,
  quantity: number,
  unitPrice: number,
  originalPrice: number,
  ownBox = false,
): OrderItem => ({ foodBagId, name, quantity, unitPrice, originalPrice, ownBox });

const money = (subtotal: number, bagSavings: number, promo = 0, box = 0): OrderMoney => ({
  subtotal,
  bagSavings,
  promoDiscount: promo,
  ownBoxDiscount: box,
  total: subtotal - promo - box,
});

const at = (date: string, time: string) => `${date}T${time}:00+07:00`;

